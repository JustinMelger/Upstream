@pytest.mark.integration
async def test_team_create_list_and_get_detail(app_client):
    """Users can create teams and see them in /teams/mine."""
    token = await _login_admin(app_client)

    created = await app_client.post(
        "/teams",
        json={"name": "Backend Guild", "description": "API reviews"},
        headers={"X-Session-Token": token},
    )
    assert created.status_code == 200
    team = created.json()
    team_id = int(team["id"])
    assert team["name"] == "Backend Guild"
    assert team["owner_user_id"] == "admin"
    assert team["member_count"] == 1
    assert team["my_role"] == "owner"
    assert len(team["members"]) == 1

    mine = await app_client.get("/teams/mine", headers={"X-Session-Token": token})
    assert mine.status_code == 200
    mine_rows = mine.json()
    matching = [row for row in mine_rows if int(row.get("id") or 0) == team_id]
    assert len(matching) == 1

    detail = await app_client.get(f"/teams/{team_id}", headers={"X-Session-Token": token})
    assert detail.status_code == 200
    assert int(detail.json()["id"]) == team_id


@pytest.mark.integration
async def test_team_member_management_permissions(app_client):
    """Only owner/admin can manage team members."""
    admin_token = await _login_admin(app_client)
    await _create_user(app_client, admin_token, "alice")
    await _create_user(app_client, admin_token, "bob")
    await _create_user(app_client, admin_token, "charlie")

    alice_token = await _login(app_client, "alice", "pass123")
    bob_token = await _login(app_client, "bob", "pass123")

    create_team = await app_client.post(
        "/teams",
        json={"name": "Data Team", "description": ""},
        headers={"X-Session-Token": alice_token},
    )
    assert create_team.status_code == 200
    team_id = int(create_team.json()["id"])

    add_bob = await app_client.post(
        f"/teams/{team_id}/members",
        json={"user_id": "bob", "role": "member"},
        headers={"X-Session-Token": alice_token},
    )
    assert add_bob.status_code == 200
    assert add_bob.json()["user_id"] == "bob"

    bob_forbidden = await app_client.post(
        f"/teams/{team_id}/members",
        json={"user_id": "charlie", "role": "member"},
        headers={"X-Session-Token": bob_token},
    )
    assert bob_forbidden.status_code == 403

    remove_owner_forbidden = await app_client.delete(
        f"/teams/{team_id}/members/alice",
        headers={"X-Session-Token": alice_token},
    )
    assert remove_owner_forbidden.status_code == 400


