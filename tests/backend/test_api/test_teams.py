@pytest.mark.integration
async def test_team_activity_lists_member_events(app_client):
    """Team activity returns share and review events generated by team members."""
    admin_token = await _login_admin(app_client)
    await _create_user(app_client, admin_token, "alice")
    await _create_user(app_client, admin_token, "bob")

    alice_token = await _login(app_client, "alice", "pass123")
    bob_token = await _login(app_client, "bob", "pass123")

    create_team = await app_client.post(
        "/teams",
        json={"name": "Review Team", "description": ""},
        headers={"X-Session-Token": alice_token},
    )
    assert create_team.status_code == 200
    team_id = int(create_team.json()["id"])

    add_bob = await app_client.post(
        f"/teams/{team_id}/members",
        json={"user_id": "bob", "role": "member"},
        headers={"X-Session-Token": alice_token},
    )
    assert add_bob.status_code == 200

    created_course = await app_client.post(
        "/courses",
        json={"title": "Team Activity Course", "description": "desc"},
        headers={"X-Session-Token": bob_token},
    )
    assert created_course.status_code == 200
    course_id = int(created_course.json()["id"])

    created_review = await app_client.post(
        f"/courses/{course_id}/reviews",
        json={"rating": 4, "text": "Solid"},
        headers={"X-Session-Token": bob_token},
    )
    assert created_review.status_code == 200

    activity = await app_client.get(f"/teams/{team_id}/activity", headers={"X-Session-Token": alice_token})
    assert activity.status_code == 200
    rows = activity.json()
    assert rows
    assert any(str(row.get("actor") or "") == "bob" for row in rows)
    assert any(str(row.get("event_type") or "") == "course_shared" for row in rows)
    assert any(str(row.get("event_type") or "") == "course_review" for row in rows)


